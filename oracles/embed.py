"""Inline format-oracle sources verbatim into generated single-file plugins.

A generated Volatility 3 plugin must be one ``.py`` file, yet it should run
the very oracle code that is tested in this repository. This module copies a
format module's source byte for byte between hash-carrying marker lines (the
block format is described in ``_inline_runtime``), so a reader can check any
inlined block against the repository with ``sha256sum``.

Two output shapes:

* :func:`inline_source` -> :class:`InlinedOracle`; its ``source`` is one
  marker-wrapped module. Pasted alone into a file it is plain, runnable
  code, but its primitives stay unbound (a format then falls back to its
  library backends) -- use :func:`render_bundle` for a real plugin.
* :func:`render_bundle` -> text for a plugin with any number of oracles and
  the primitives they require (each primitive once, ahead of the oracles):
  the inline runtime as plain code, then a raw string holding every block.
  ``load_inlined(kind, MEMDIVER_INLINED_SOURCES)`` executes a block in its
  own module after re-checking its hash, so module-level names of different
  oracles can never collide and the code that runs is the code that was
  hashed. That holds for the inlined blocks; the runtime and the plugin
  template run as plain code, checked by ``verify_inlined`` over the whole file.
"""
from __future__ import annotations

import ast
import importlib.util
from dataclasses import dataclass
from pathlib import Path
from types import ModuleType
from typing import Iterable

from . import PRIMITIVES_PACKAGE, PRIMITIVES_SUBDIR, _inline_runtime, get_format
from ._inline_runtime import (  # noqa: F401 - re-exported API
    InlinedBlock,
    extract_inlined,
    inline_marker,
    inline_sha256,
    load_inlined,
    verify_inlined,
)

REPO_ROOT = Path(__file__).resolve().parent.parent
# PRIMITIVES_PACKAGE / PRIMITIVES_SUBDIR (where the stdlib-only crypto primitives
# named by REQUIRES_PRIMITIVES live) are defined in the registry, which binds the
# same modules in-repo, and re-exported here.


class MissingPrimitiveError(FileNotFoundError):
    """A format declares a primitive whose source file does not exist."""


def default_primitives_dir() -> Path:
    """``<memdiver.vol3plugins>/linux/secrets`` wherever memdiver is installed.

    Located with ``importlib.util.find_spec`` on the top package only, so
    nothing under it is imported; falls back to the repository layout.
    """
    try:
        spec = importlib.util.find_spec(PRIMITIVES_PACKAGE)
    except (ImportError, ValueError):
        spec = None
    for location in (spec.submodule_search_locations or []) if spec else []:
        candidate = Path(location).joinpath(*PRIMITIVES_SUBDIR)
        if candidate.is_dir():
            return candidate
    return REPO_ROOT.joinpath("vol3plugins", *PRIMITIVES_SUBDIR)
#: Name of the raw-string constant that holds the blocks in a rendered bundle.
BUNDLE_SOURCES_NAME = "MEMDIVER_INLINED_SOURCES"

_BUNDLE_HEADER = f"""\
# ==========================================================================
# memdiver inlined oracles -- generated by memdiver.oracles.embed.render_bundle
#
# (1) The inline runtime below is plain code. (2) {BUNDLE_SOURCES_NAME} is a
# raw string holding the verbatim source of every oracle and primitive. Each
# block sits between "memdiver <role>:<name> sha256=... begin/end" marker
# lines; the sha256 covers the exact text between them, i.e. it equals
# sha256sum of the repository file the block was copied from.
# load_inlined("<kind>", {BUNDLE_SOURCES_NAME}) re-checks that hash and runs
# the block in its own module object, so oracles cannot clash by name.
# ==========================================================================
"""


@dataclass(frozen=True)
class InlinedPrimitive:
    """One primitive module, marker-wrapped."""

    name: str
    source: str
    sha256: str


@dataclass(frozen=True)
class InlinedOracle:
    """One format module, marker-wrapped, plus the primitives it requires."""

    kind: str
    source: str
    sha256: str
    primitives: tuple[InlinedPrimitive, ...] = ()


def read_paste_safe_source(path: str | Path) -> str:
    """Exact text of a module file, refusing anything that would not survive inlining."""
    text = Path(path).read_bytes().decode("utf-8")
    if not text.endswith("\n") or "\r" in text:
        raise ValueError(f"{path}: source must use '\\n' line endings and end with one")
    if any(line.startswith("# --- memdiver ") for line in text.split("\n")):
        raise ValueError(f"{path}: a line starts with the inline block marker")
    return text


def wrap_block(role: str, name: str, text: str) -> tuple[str, str]:
    """``(marker-wrapped text, sha256)`` for one block."""
    sha = inline_sha256(text)
    return inline_marker(role, name, sha, "begin") + text + inline_marker(role, name, sha, "end"), sha


def inline_source(kind: str, *, primitives_dir: str | Path | None = None) -> InlinedOracle:
    """Marker-wrapped source of the registered format ``kind`` (+ its primitives)."""
    return inline_module(get_format(kind), primitives_dir=primitives_dir)


def inline_module(module: ModuleType, *, primitives_dir: str | Path | None = None) -> InlinedOracle:
    """Marker-wrapped source of a format ``module`` loaded from a file."""
    if module.__file__ is None:
        raise ValueError(f"{module.__name__} has no source file to inline")
    wrapped, sha = wrap_block("oracle", module.KIND, read_paste_safe_source(module.__file__))
    primitives = _inline_primitives(
        module.KIND, getattr(module, "REQUIRES_PRIMITIVES", ()),
        Path(primitives_dir) if primitives_dir else default_primitives_dir(),
    )
    return InlinedOracle(module.KIND, wrapped, sha, primitives)


def _inline_primitives(
    kind: str, names: Iterable[str], directory: Path
) -> tuple[InlinedPrimitive, ...]:
    """Each declared primitive once. A missing one is fatal: a plugin silently
    lacking it could not prove anything on a host without ``cryptography``."""
    primitives = []
    for name in dict.fromkeys(names):
        path = directory / f"{name}.py"
        if not path.is_file():
            raise MissingPrimitiveError(f"{kind} requires primitive {name!r}, but {path} is missing")
        wrapped, sha = wrap_block("primitive", name, read_paste_safe_source(path))
        primitives.append(InlinedPrimitive(name, wrapped, sha))
    return tuple(primitives)


def runtime_block() -> str:
    """The inline runtime (``_inline_runtime.py``) as a marker-wrapped block of plain code."""
    wrapped, _ = wrap_block(
        "runtime", "inline-loader", read_paste_safe_source(_inline_runtime.__file__)
    )
    return wrapped


def render_bundle(
    oracles: Iterable[str | InlinedOracle], *, primitives_dir: str | Path | None = None
) -> str:
    """Python text for a plugin: the runtime, then one raw string with every block.

    ``oracles`` are format KINDs or ready :class:`InlinedOracle` objects.
    Primitives are emitted once each, ahead of the oracles.
    """
    inlined = [
        item if isinstance(item, InlinedOracle)
        else inline_source(item, primitives_dir=primitives_dir)
        for item in oracles
    ]
    payload = "".join(_unique_primitive_sources(inlined) + [o.source for o in inlined])
    quote = _raw_string_quote(payload)
    bundle = (
        f"{_BUNDLE_HEADER}{runtime_block()}\n"
        f"{BUNDLE_SOURCES_NAME} = r{quote}\n{payload}{quote}\n"
    )
    _self_check(bundle, quote, payload)
    return bundle


def _unique_primitive_sources(inlined: list[InlinedOracle]) -> list[str]:
    seen: dict[str, InlinedPrimitive] = {}
    for primitive in (p for o in inlined for p in o.primitives):
        if seen.setdefault(primitive.name, primitive).sha256 != primitive.sha256:
            raise ValueError(f"two different versions of primitive {primitive.name!r}")
    return [p.source for p in seen.values()]


def _raw_string_quote(payload: str) -> str:
    for quote in ("'''", '"""'):
        if quote not in payload:
            return quote
    raise ValueError("inlined sources contain both ''' and \"\"\"; cannot embed as a raw string")


def _self_check(bundle: str, quote: str, payload: str) -> None:
    """The rendered literal must evaluate to the payload and every block must verify."""
    if ast.literal_eval(f"r{quote}\n{payload}{quote}") != f"\n{payload}":
        raise ValueError("raw-string embedding altered the inlined sources")
    compile(bundle, "<memdiver bundle>", "exec")
    if not verify_inlined(bundle):
        raise ValueError("rendered bundle fails verify_inlined")
