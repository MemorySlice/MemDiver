"""Every checked-in plaintext .msl fixture must pass ``verify_chain``.

Spec §4.4: Block 0 PrevHash = hash of all HeaderSize header bytes, block i =
hash of block i-1. Generated fixtures are regenerated by their generators
(which chain PrevHash), so they must verify with no legacy tolerance. Files
that cannot be repaired are allowlisted with the exact failure they show, so
the check stays meaningful (see tests/fixtures/real_samples/README.md).
"""

from pathlib import Path

import pytest

pytest.importorskip("blake3")

from memdiver.msl.enums import HeaderFlag  # noqa: E402
from memdiver.msl.hashing import hash_bytes  # noqa: E402
from memdiver.msl.integrity import verify_chain  # noqa: E402
from memdiver.msl.reader import MslReader  # noqa: E402

_TESTS = Path(__file__).resolve().parent
_FIXTURE_ROOTS = (_TESTS / "fixtures", _TESTS / "e2e" / "fixtures")
_FLAGS_OFFSET = 0x0C

# Real capture whose header byte 0x0B was hand-patched 0x00 -> 0x01
# (Version 0.1 -> 1.1) after capture; not regenerable.
_CHROME_MIN = _TESTS / "fixtures" / "real_samples" / "chrome_min.msl"
_KNOWN_MODIFIED_HEADER = {_CHROME_MIN: (0x0B, 0x00)}

# Fixtures the e2e specs / tests rely on; they must exist so this test
# cannot pass vacuously.
_REQUIRED = (
    _TESTS / "e2e" / "fixtures" / "synthetic_msl" / "sample.msl",
    _TESTS / "e2e" / "fixtures" / "aslr_msl" / "run_1.msl",
    _TESTS / "e2e" / "fixtures" / "aslr_msl" / "run_2.msl",
    _TESTS / "e2e" / "fixtures" / "pcap" / "matched.msl",
    _CHROME_MIN,
)


def _is_encrypted(path: Path) -> bool:
    raw = path.read_bytes()[:_FLAGS_OFFSET + 4]
    return bool(int.from_bytes(raw[_FLAGS_OFFSET:], "little") & HeaderFlag.ENCRYPTED)


def _plaintext_fixtures():
    found = sorted(p for root in _FIXTURE_ROOTS for p in root.rglob("*.msl"))
    return [p for p in found if not _is_encrypted(p)]


def _report(path: Path):
    with MslReader(path) as reader:
        return verify_chain(reader), reader.file_header.header_size


def _ids(paths):
    return [str(p.relative_to(_TESTS)) for p in paths]


_FIXTURES = _plaintext_fixtures()
_CHAINED = [p for p in _FIXTURES if p not in _KNOWN_MODIFIED_HEADER]


def test_required_fixtures_present():
    missing = [str(p) for p in _REQUIRED if not p.is_file()]
    assert not missing, f"expected checked-in fixtures missing: {missing}"


@pytest.mark.parametrize("path", _CHAINED, ids=_ids(_CHAINED))
def test_fixture_chain_verifies(path):
    report, _ = _report(path)
    assert report.valid, report.errors
    assert not report.legacy_unchained_header, (
        f"{path.name}: zero Block-0 PrevHash; regenerate it with its generator")
    assert report.block_count >= 1


@pytest.mark.parametrize("path", list(_KNOWN_MODIFIED_HEADER),
                         ids=_ids(_KNOWN_MODIFIED_HEADER))
def test_known_modified_header_fails_only_at_block0(path):
    report, header_size = _report(path)
    assert not report.valid
    assert report.broken_at == header_size, report.errors
    assert len(report.errors) == 1, report.errors  # every later link intact


@pytest.mark.parametrize("path", list(_KNOWN_MODIFIED_HEADER),
                         ids=_ids(_KNOWN_MODIFIED_HEADER))
def test_known_modified_header_original_byte_reconstructs_prev_hash(path):
    offset, original = _KNOWN_MODIFIED_HEADER[path]
    raw = path.read_bytes()
    header_size = raw[9]
    header = bytearray(raw[:header_size])
    header[offset] = original
    block0_prev_hash = raw[header_size + 0x30:header_size + 0x50]
    assert hash_bytes(bytes(header)) == block0_prev_hash


# ---------------------------------------------------------------------------
# Generators: every top-level assembler emits a spec-chained file.
# ---------------------------------------------------------------------------

def _verify_bytes(tmp_path: Path, name: str, blob: bytes):
    path = tmp_path / name
    path.write_bytes(blob)
    report, _ = _report(path)
    assert report.valid, report.errors
    assert not report.legacy_unchained_header
    return report


def test_generate_msl_file_is_chained(tmp_path):
    from tests.fixtures.generate_msl_fixtures import generate_msl_file
    assert _verify_bytes(tmp_path, "gen.msl", generate_msl_file()).block_count == 18


def test_generate_msl_file_is_deterministic():
    from tests.fixtures.generate_msl_fixtures import generate_msl_file
    assert generate_msl_file() == generate_msl_file()


def test_chain_prev_hashes_only_touches_prev_hash_slots():
    from tests.fixtures import generate_msl_fixtures as gm
    chained = gm.generate_msl_file()
    zeroed = bytearray(chained)
    offset = chained[9]
    while offset < len(zeroed):
        zeroed[offset + 0x30:offset + 0x50] = b"\x00" * 32
        offset += int.from_bytes(chained[offset + 8:offset + 12], "little")
    assert gm.chain_prev_hashes(bytes(zeroed)) == chained


def test_write_aslr_fixture_is_chained(tmp_path):
    from tests.fixtures.generate_msl_fixtures import write_aslr_fixture
    path = write_aslr_fixture(tmp_path / "a.msl", region_base=0x7F0000000000)
    _verify_bytes(tmp_path, "a2.msl", path.read_bytes())


@pytest.mark.parametrize("algo", ["zstd", "lz4"])
def test_write_compressed_fixture_is_chained(tmp_path, algo):
    from tests.fixtures.generate_msl_fixtures import write_compressed_msl_fixture
    path = write_compressed_msl_fixture(tmp_path / f"{algo}.msl", algo=algo)
    if path is None:
        pytest.skip(f"{algo} unavailable")
    _verify_bytes(tmp_path, f"{algo}2.msl", path.read_bytes())


def test_aslr_pair_is_chained(tmp_path):
    from tests.fixtures.generate_msl_aslr_fixtures import generate_aslr_msl_pair
    for extra in (False, True):
        for i, blob in enumerate(generate_aslr_msl_pair(extra_region=extra)):
            _verify_bytes(tmp_path, f"run{i}_{extra}.msl", blob)


def test_ensure_msl_fixtures_replaces_a_stale_gitignored_copy(tmp_path):
    """A stale test_capture.msl (e.g. zero PrevHash from an old generator)
    left in a clone is regenerated instead of silently reused."""
    from tests.fixtures.generate_msl_fixtures import ensure_msl_fixtures

    ensure_msl_fixtures(tmp_path)
    fixture = tmp_path / "msl" / "test_capture.msl"
    good = fixture.read_bytes()
    stale = bytearray(good)
    stale[0xC8 + 0x30:0xC8 + 0x50] = b"\x00" * 32  # block 1 PrevHash
    fixture.write_bytes(bytes(stale))
    ensure_msl_fixtures(tmp_path)
    assert fixture.read_bytes() == good
