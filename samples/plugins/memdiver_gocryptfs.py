def error_code(detail):
    """``error:<slug>`` from a verdict detail: whole words, at most ERROR_CODE_MAX chars."""
    words = re.findall(r"[a-z0-9]+", str(detail).split(";")[0].lower())
    slug = ""
    for word in words:
        candidate = word if not slug else slug + "-" + word
        if len(candidate) > ERROR_CODE_MAX:
            break
        slug = candidate
    return "error:%s" % (slug or "oracle")


def parse_oracle_params(items):
    """``["cipher=aes-gcm", "hkdf=false", "nonce_length=12"]`` -> a params dict."""
    params = {}
    for item in items or []:
        if "=" not in item:
            raise ValueError("--oracle-param %r is not key=value" % (item,))
        key, value = item.split("=", 1)
        lowered = value.strip().lower()
        if lowered in ("true", "false"):
            params[key.strip()] = lowered == "true"
        elif lowered in ("none", "null"):
            params[key.strip()] = None
        elif re.match(r"^-?[0-9]+$", lowered):
            params[key.strip()] = int(lowered)
        else:
            params[key.strip()] = value.strip()
    return params


def check_sample_dir(path):
    """Refuse a directory too deep or too big to be one artefact (bounded walk)."""
    base = os.path.abspath(path)
    files = 0
    for root, _dirs, names in os.walk(base):
        depth = 0 if root == base else os.path.relpath(root, base).count(os.sep) + 1
        if depth > SAMPLE_DIR_MAX_DEPTH:
            raise ValueError("--oracle-sample is deeper than %d levels; point it at the "
                             "artefact directory itself (%s)" % (SAMPLE_DIR_MAX_DEPTH, path))
        files += len(names)
        if files > SAMPLE_DIR_MAX_FILES:
            raise ValueError("--oracle-sample holds over %d files; point it at the "
                             "artefact directory itself (%s)" % (SAMPLE_DIR_MAX_FILES, path))


def shannon_entropy(data):
    """Shannon entropy of ``data`` in bits per byte."""
    if not data:
        return 0.0
    counts = {}
    for value in data:
        counts[value] = counts.get(value, 0) + 1
    total = float(len(data))
    return -sum((c / total) * math.log2(c / total) for c in counts.values())


def wildcard_to_regex(tokens):
    """``"aa ?? bb"`` -> a bytes regex; runs of ``??`` become ``.{n}``."""
    parts, wild = [], 0
    for token in tokens.split():
        if token == "??":
            wild += 1
            continue
        if wild:
            parts.append(b".{%d}" % wild)
            wild = 0
        parts.append(re.escape(bytes((int(token, 16),))))
    if wild:
        parts.append(b".{%d}" % wild)
    # A zero-width lookahead reports OVERLAPPING matches too (finditer would
    # skip a real match that overlaps a false one); DOTALL lets "." match \n.
    return b"(?=" + b"".join(parts) + b")"


class EntropyCapReached(Exception):
    """Raised by EntropyScanner on the chunk AFTER its cap: stops the layer read."""


class EntropyScanner(interfaces.layers.ScannerInterface):
    """Yield ``(offset, window)`` for high-entropy windows of ``window`` bytes.

    Cheap stage first: every ``block``-byte block of the chunk is flagged when
    it holds at least ``block_min_distinct`` distinct byte values; a window is
    examined only when every block lying fully inside it is flagged. Survivors
    must hold enough distinct values to reach ``threshold`` and then reach it.
    Only window starts that are multiples of ``step`` (absolute) are tried.
    """

    thread_safe = False

    def __init__(self, window, threshold, step, block=16, block_min_distinct=12,
                 max_candidates=500000):
        super().__init__()
        self.window = int(window)
        self.threshold = float(threshold)
        self.step = max(1, int(step))
        # A block must fit inside a window at any alignment, or no window passes.
        self.block = max(4, min(int(block), self.window // 2))
        self.block_min_distinct = int(block_min_distinct)
        self.min_distinct = int(math.ceil(2 ** self.threshold - 1e-9))
        self.max_candidates = int(max_candidates)
        self.examined = 0
        self.found = 0
        self.truncated = False
        self.stopped_at = None   # first address NOT covered once truncated

    def __call__(self, data, data_offset):
        if self.found >= self.max_candidates:
            self.truncated = True
            if self.stopped_at is None:
                self.stopped_at = data_offset
            # Every earlier chunk's windows were already consumed (the scan is
            # sequential for a non-thread-safe scanner); reading on is waste.
            raise EntropyCapReached()
        size, block, width = len(data), self.block, self.window
        flags = [len(set(data[i:i + block])) >= self.block_min_distinct
                 for i in range(0, size - block + 1, block)]
        last_start = min(size - width, self.chunk_size - 1)
        index = 0
        while index < len(flags):
            if not flags[index]:
                index += 1
                continue
            run_end = index
            while run_end < len(flags) and flags[run_end]:
                run_end += 1
            for offset, window in self._windows(data, data_offset, flags, index, run_end,
                                                last_start):
                yield offset, window
            index = run_end

    def _windows(self, data, data_offset, flags, run_start, run_end, last_start):
        block, width, step = self.block, self.window, self.step
        lo = max(0, run_start * block - block + 1)
        hi = min(last_start, run_end * block + block - 1 - width)
        first = lo + (-(data_offset + lo)) % step
        for start in range(first, hi + 1, step):
            full_lo = -(-start // block)
            full_hi = (start + width) // block
            if full_hi <= full_lo or not all(flags[full_lo:full_hi]):
                continue
            window = data[start:start + width]
            self.examined += 1
            if len(set(window)) < self.min_distinct:
                continue
            if shannon_entropy(window) < self.threshold:
                continue
            self.found += 1
            if self.found > self.max_candidates:
                self.truncated = True
                self.stopped_at = data_offset + start
                return
            yield data_offset + start, window


class PrimaryOrKernelLayer(requirements.TranslationLayerRequirement):
    """A mandatory layer requirement that the kernel module's layer also satisfies.

    Mandatory, so the LayerStacker runs at all (it only stacks when some
    non-optional requirement is unsatisfied); satisfied by ``kernel.layer_name``
    so the stacker may put the image under the ``kernel`` module instead,
    where the symbol automagic can turn it into a real kernel module.
    """

    def unsatisfied(self, context, config_path):
        own = interfaces.configuration.path_join(config_path, self.name)
        kernel_layer = interfaces.configuration.path_join(config_path, "kernel", "layer_name")
        if context.config.get(own, None) is None and context.config.get(kernel_layer, None):
            return {}
        return super().unsatisfied(context, config_path)


class Candidate(object):
    """One unique candidate key, the places it was found and its verdict."""

    def __init__(self, key):
        self.key = key
        self.sites = []          # (key_offset, pattern_offset, static_ratio, locator)
        self.locators = []
        self.proven = "unverified"
        self.site_scopes = {}    # key_offset -> Scope of the layer it was read from
        self.detail = ""

    def add_site(self, key_offset, pattern_offset, static_ratio, locator):
        if locator not in self.locators:
            self.locators.append(locator)
        if len(self.sites) < MAX_OFFSETS_PER_CANDIDATE and all(
                site[0] != key_offset for site in self.sites):
            self.sites.append((key_offset, pattern_offset, static_ratio, locator))

    @property
    def is_proven(self):
        return self.proven.startswith("oracle:")


class MemDiverSynthGocryptfs(interfaces.plugins.PluginInterface):
    """Find and prove the secret described by recipe memdiver_gocryptfs."""

    _required_framework_version = (2, 0, 0)
    _version = (1, 0, 0)

